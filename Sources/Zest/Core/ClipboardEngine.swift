import Foundation
import AppKit

@MainActor
public class ClipboardEngine: ObservableObject {
    public static let shared = ClipboardEngine()

    @Published public private(set) var items: [ClipItem] = []
    @Published public var isPaused: Bool = false
    
    private let pasteboard = NSPasteboard.general
    private var lastChangeCount: Int
    private var timer: Timer?

    private init() {
        self.lastChangeCount = pasteboard.changeCount
        self.items = HistoryStorageManager.shared.load()
    }

    public func start(pollingInterval: TimeInterval = 0.4) {
        timer?.invalidate()
        let t = Timer(timeInterval: pollingInterval, repeats: true) { [weak self] _ in
            Task { @MainActor in
                self?.poll()
            }
        }
        RunLoop.main.add(t, forMode: .common)
        timer = t
    }

    public func stop() {
        timer?.invalidate()
        timer = nil
    }

    public func clearAll() {
        items.removeAll()
        HistoryStorageManager.shared.save(items: items)
    }

    public func togglePin(for itemID: UUID) {
        if let idx = items.firstIndex(where: { $0.id == itemID }) {
            items[idx].isPinned.toggle()
            HistoryStorageManager.shared.save(items: items)
        }
    }

    public func delete(itemID: UUID) {
        items.removeAll { $0.id == itemID }
        HistoryStorageManager.shared.save(items: items)
    }

    public func add(text: String, sourceApp: String? = nil) {
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.isEmpty else { return }
        let newItem = ClipItem(rawContent: text, sourceApp: sourceApp)
        items.insert(newItem, at: 0)
        pruneHistoryIfNeeded()
        HistoryStorageManager.shared.save(items: items)
    }

    public func add(image: Data, width: Int, height: Int, sourceApp: String? = nil) {
        handleImageCopied(pngData: image, width: width, height: height, frontApp: sourceApp)
    }

    public func isAppIgnored(bundleID: String) -> Bool {
        let ignoredApps = UserDefaults.standard.stringArray(forKey: "zest_ignoredAppBundleIDs")
            ?? []
        return ignoredApps.contains(bundleID)
    }

    private func poll() {
        guard !isPaused else { return }
        guard pasteboard.changeCount != lastChangeCount else { return }
        lastChangeCount = pasteboard.changeCount

        // 1. Skip self-copies
        if let types = pasteboard.types, types.contains(.fromZest) {
            return
        }

        // 2. Ignore password managers & ephemeral items
        if let types = pasteboard.types {
            let ignored: Set<NSPasteboard.PasteboardType> = [.concealed, .transient, .autoGenerated]
            if !ignored.isDisjoint(with: Set(types)) {
                return
            }
        }

        // 3. Check App Blacklist (Ignored Applications)
        if let currentAppBundleID = NSWorkspace.shared.frontmostApplication?.bundleIdentifier {
            if isAppIgnored(bundleID: currentAppBundleID) {
                return
            }
        }

        let frontApp = NSWorkspace.shared.frontmostApplication?.localizedName
        let types = pasteboard.types ?? []

        let stringContent = pasteboard.string(forType: .string)
        let trimmedString = stringContent?.trimmingCharacters(in: .whitespacesAndNewlines)
        let hasValidText = (trimmedString != nil && !trimmedString!.isEmpty)

        // 4. Extract Image content
        // Rich text apps (Word, Pages, TextEdit, WebKit) place both text and a rendered .tiff on pasteboard.
        // If valid text is present and there's no standalone PNG, prioritize text over TIFF image.
        let isPureImage = (types.contains(.png) && !hasValidText) || (types.contains(.tiff) && !hasValidText)
        let isPngWithoutString = types.contains(.png) && !types.contains(.string)

        if isPureImage || isPngWithoutString {
            if let (pngData, width, height) = extractImageData() {
                handleImageCopied(pngData: pngData, width: width, height: height, frontApp: frontApp)
                return
            }
        }

        // 5. Extract text content
        if let string = stringContent, hasValidText {
            handleTextCopied(string: string, frontApp: frontApp)
            return
        }

        // 6. Fallback for pure image where text was empty
        if types.contains(.png) || types.contains(.tiff) {
            if let (pngData, width, height) = extractImageData() {
                handleImageCopied(pngData: pngData, width: width, height: height, frontApp: frontApp)
                return
            }
        }
    }

    private func extractImageData() -> (data: Data, width: Int, height: Int)? {
        // 1. Prefer PNG if available
        if let pngData = pasteboard.data(forType: .png) {
            if let rep = NSBitmapImageRep(data: pngData) {
                return (pngData, rep.pixelsWide, rep.pixelsHigh)
            } else if let img = NSImage(data: pngData) {
                return (pngData, Int(img.size.width), Int(img.size.height))
            }
        }

        // 2. Fall back to TIFF, converting to compressed PNG for storage
        if let tiffData = pasteboard.data(forType: .tiff) {
            if let rep = NSBitmapImageRep(data: tiffData),
               let pngData = rep.representation(using: .png, properties: [:]) {
                return (pngData, rep.pixelsWide, rep.pixelsHigh)
            } else if let img = NSImage(data: tiffData),
                      let tiff = img.tiffRepresentation,
                      let rep = NSBitmapImageRep(data: tiff),
                      let pngData = rep.representation(using: .png, properties: [:]) {
                return (pngData, rep.pixelsWide, rep.pixelsHigh)
            }
        }

        return nil
    }

    private func handleImageCopied(pngData: Data, width: Int, height: Int, frontApp: String?) {
        // Deduplicate using imageData equality (LRU move-to-front)
        if let existingIdx = items.firstIndex(where: { $0.imageData == pngData }) {
            var existing = items.remove(at: existingIdx)
            existing.lastCopiedAt = Date()
            existing.copyCount += 1
            if existing.sourceApp == nil { existing.sourceApp = frontApp }
            items.insert(existing, at: 0)
        } else {
            let title = "Image (\(width) × \(height))"
            let newItem = ClipItem(
                rawContent: title,
                imageData: pngData,
                imageWidth: width,
                imageHeight: height,
                sourceApp: frontApp,
                detectedType: .image
            )
            items.insert(newItem, at: 0)
            pruneHistoryIfNeeded()
        }
        HistoryStorageManager.shared.save(items: items)
    }

    private func handleTextCopied(string: String, frontApp: String?) {
        if let existingIdx = items.firstIndex(where: { $0.rawContent == string && !$0.isImage }) {
            var existing = items.remove(at: existingIdx)
            existing.lastCopiedAt = Date()
            existing.copyCount += 1
            if existing.sourceApp == nil { existing.sourceApp = frontApp }
            items.insert(existing, at: 0)
        } else {
            let newItem = ClipItem(
                rawContent: string,
                sourceApp: frontApp
            )
            items.insert(newItem, at: 0)
            pruneHistoryIfNeeded()
        }
        HistoryStorageManager.shared.save(items: items)
    }

    private func pruneHistoryIfNeeded() {
        let maxLimit = HistoryStorageManager.shared.maxHistoryLimit
        if items.count > maxLimit {
            if let lastUnpinnedIdx = items.lastIndex(where: { !$0.isPinned }) {
                items.remove(at: lastUnpinnedIdx)
            } else {
                items.removeLast()
            }
        }
    }
}
